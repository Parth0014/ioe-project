async (page) => {
  page.setDefaultTimeout(10000);
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('http://127.0.0.1:8876/analytics');
  await page.locator('#report').waitFor({state:'visible'});
  if((await page.locator('#source').textContent())!=='Local SQLite')throw new Error('Python analytics did not use local SQLite');
  if(await page.locator('#mode').count())throw new Error('Analytics still exposes a reading-mode selector');
  if((await page.locator('body').textContent()).includes('Demo data'))throw new Error('Analytics still references demo data');
  if(!(await page.locator('.app-header').count())||!(await page.locator('.view-nav').count()))throw new Error('Analytics does not use the dashboard shell');
  await page.getByRole('radio',{name:'30 days',exact:true}).check();
  await page.waitForFunction(()=>!document.querySelector('#report').hidden&&document.querySelector('#table-body').children.length>=30);
  const oldRow=await page.locator('#table-body tr').first().elementHandle();
  await page.getByRole('button',{name:'Refresh data',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#refresh').disabled);
  if(!(await oldRow.evaluate(el=>el.isConnected)))throw new Error('Unchanged analytics table rebuilt on refresh');
  await page.setViewportSize({width:390,height:844});
  if(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth))throw new Error('Analytics has horizontal overflow');
  await page.screenshot({path:'output/playwright/analytics-local-phone.png',fullPage:true});
  await page.setViewportSize({width:1440,height:900});
  await page.screenshot({path:'output/playwright/analytics-local-desktop.png'});
  await page.getByRole('link',{name:'Dashboard',exact:true}).click();
  await page.waitForURL(url=>url.pathname==='/'&&!url.hash);
  await page.getByRole('link',{name:'Analytics',exact:true}).click();
  await page.waitForURL('**/analytics');
  await page.getByRole('link',{name:'Developer debugging',exact:true}).click();
  await page.waitForURL(url=>url.pathname==='/'&&url.hash==='#debugging');
  await page.getByRole('heading',{name:'Developer debugging',exact:true}).waitFor();
  if(errors.length)throw new Error(errors.join('; '));
  return {consistentShell:true,routing:true,localSQLite:true,unchangedTableRetained:true,phoneLayout:true,pageErrors:errors};
}
